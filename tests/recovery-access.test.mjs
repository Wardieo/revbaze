import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const entries = new Map();
globalThis.localStorage = { getItem: key => entries.get(key) ?? null, setItem: (key, value) => entries.set(key, value), removeItem: key => entries.delete(key) };
globalThis.window = { location: { href: 'https://example.com/?auth_callback=recovery' }, setTimeout };
let event;
const auth = { onAuthStateChange: callback => { event = callback; }, getSession: () => Promise.resolve({ data: { session: null } }) };
const raw = (await readFile('src/lib/supabase.ts', 'utf8')).replaceAll('import.meta.env.VITE_SUPABASE_URL', '"https://test.supabase.co"').replaceAll('import.meta.env.VITE_SUPABASE_PUBLISHABLE_KEY', '"test-key"');
const code = ts.transpileModule(raw, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const exports = {};
new Function('require', 'exports', code)(name => name.includes('supabase-js') ? { createClient: () => ({ auth }) } : name === './auth' ? { callbackDetails: () => ({ active: false, recovery: true }) } : { createAuthFetch: () => fetch }, exports);
exports.authCallback.active = true;
event('PASSWORD_RECOVERY', { user: { id: 'recovering-user' } });
assert(exports.isPasswordRecoverySession('recovering-user'));
assert(!exports.isPasswordRecoverySession('other-user'));
assert(exports.canResetPassword('recovering-user'));
assert.equal(localStorage.getItem('revbaze-password-recovery-user'), 'recovering-user');
exports.clearPasswordRecovery();
assert(!exports.isPasswordRecoverySession('recovering-user'));
localStorage.setItem('revbaze-password-recovery-user', 'recovering-user');
assert(exports.isPasswordRecoverySession('recovering-user'), 'Reloaded recovery sessions remain restricted');
assert(!exports.canResetPassword('recovering-user'), 'Reload alone does not authorize a new password reset');
event('SIGNED_OUT', null);
exports.authCallback.active = false;
await exports.authBootstrap;
assert(!exports.isPasswordRecoverySession('recovering-user'));
console.log('Recovery restriction tests passed: email recovery, reload persistence, user isolation, completion and logout.');
